import { test, expect } from '@playwright/test';

test('desktop mode selection, movement, pause, resume, and arcade cleanup', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  await page.goto('/');
  await page.screenshot({ path: '.runtime/maze-screenshots/maze-menu-desktop.png', fullPage: true });
  await page.locator('#open-maze').click();
  await expect(page.locator('#maze-mode-screen')).toBeVisible();
  await page.locator('[data-maze-mode="persist"]').click();
  await page.locator('#maze-start-run').click();
  await expect(page.locator('#maze-game-screen')).toBeVisible();
  await expect(page.locator('#maze-mode-readout')).toHaveText('PERSIST + ADD');
  const canvas = page.locator('#maze-board');
  await page.screenshot({ path: '.runtime/maze-screenshots/maze-board-desktop.png', fullPage: true });
  await expect.poll(() => canvas.evaluate((node) => node.toDataURL())).not.toBe('');
  await page.keyboard.press('Space');
  await expect(page.locator('#maze-status-text')).toHaveText('PAUSED');
  const pausedFrame = await canvas.evaluate((node) => node.toDataURL());
  await page.waitForTimeout(180);
  expect(await canvas.evaluate((node) => node.toDataURL())).toBe(pausedFrame);
  await page.keyboard.press('Space');
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await expect.poll(() => canvas.evaluate((node) => node.toDataURL())).not.toBe(pausedFrame);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await expect(page.locator('#maze-status-text')).toHaveText('PAUSED');
  await page.locator('#maze-settings').click();
  await expect(page.locator('#maze-resume-current')).toBeVisible();
  await page.locator('#maze-resume-current').click();
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await page.locator('.brand').click();
  await expect(page.locator('#home')).toBeVisible();
  await expect(page.locator('#maze-view')).toBeHidden();
  expect(pageErrors).toEqual([]);
});

test('keyboard shortcuts leave focused mode, resume, action, and arcade buttons to native activation', async ({ page }) => {
  await page.addInitScript(() => { Math.random = () => 0.5; });
  await page.goto('/');
  await page.locator('#open-maze').focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#maze-mode-title')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.locator('[data-maze-mode="refresh"]')).toBeFocused();
  for (const key of ['ArrowUp', 'ArrowDown', 'w', 's']) {
    await page.keyboard.press(key);
    await expect(page.locator('[data-maze-mode="persist"]')).toBeFocused();
    await expect(page.locator('[data-maze-mode="persist"]')).toHaveAttribute('aria-pressed', 'true');
    await page.keyboard.press(key);
    await expect(page.locator('[data-maze-mode="refresh"]')).toBeFocused();
    await expect(page.locator('[data-maze-mode="refresh"]')).toHaveAttribute('aria-pressed', 'true');
  }
  await page.keyboard.press('ArrowDown');
  await expect(page.locator('[data-maze-mode="persist"]')).toBeFocused();
  await page.keyboard.press('Space');
  await expect(page.locator('[data-maze-mode="persist"]')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('#maze-mode-screen')).toBeVisible();
  await page.keyboard.press('Enter');
  await expect(page.locator('[data-maze-mode="persist"]')).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('Tab');
  await expect(page.locator('#maze-pregame-settings')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('.settings-dialog[open]')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.locator('#maze-pregame-settings')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.locator('#maze-start-run')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('#maze-mode-readout')).toHaveText('PERSIST + ADD');

  await expect(page.locator('#maze-pause')).toBeFocused();
  await page.keyboard.press('Space');
  await expect(page.locator('#maze-status-text')).toHaveText('PAUSED');
  await page.keyboard.press('Enter');
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await page.keyboard.press('Tab');
  await expect(page.locator('#maze-settings')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('[data-maze-mode="persist"]')).toBeFocused();
  await expect(page.locator('[data-maze-mode="persist"]')).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('ArrowDown');
  await expect(page.locator('[data-maze-mode="refresh"]')).toBeFocused();
  await expect(page.locator('[data-maze-mode="refresh"]')).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('ArrowUp');
  await expect(page.locator('[data-maze-mode="persist"]')).toBeFocused();
  await page.keyboard.press('w');
  await expect(page.locator('[data-maze-mode="refresh"]')).toBeFocused();
  await page.keyboard.press('s');
  await expect(page.locator('[data-maze-mode="persist"]')).toBeFocused();
  await page.keyboard.press('Tab');
  await page.keyboard.press('Tab');
  await page.keyboard.press('Tab');
  await expect(page.locator('#maze-resume-current')).toBeFocused();
  await page.keyboard.press('Space');
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await page.keyboard.press('ArrowUp');
  await expect(page.locator('#maze-status-text')).toHaveText('RUN OVER', { timeout: 2000 });
  await page.keyboard.press('r');
  await expect(page.locator('[data-maze-mode="persist"]')).toBeFocused();
  await expect(page.locator('[data-maze-mode="persist"]')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('[data-maze-mode="refresh"]')).toHaveAttribute('aria-pressed', 'false');

  await page.keyboard.press('Escape');
  await page.locator('#open-maze').focus();
  await page.keyboard.press('Space');
  await expect(page.locator('#maze-mode-screen')).toBeVisible();
  await page.keyboard.press('Shift+Tab');
  await expect(page.locator('#maze-home')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('#home')).toBeVisible();

  await page.locator('#open-maze').focus();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Space');
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await page.keyboard.press('Escape');
});

test('mobile Space start, real touch steering, zoom containment, restart, and home', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 320, height: 720 }, isMobile: true, hasTouch: true });
  await context.addInitScript(() => { Math.random = () => 0.5; });
  const page = await context.newPage();
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  await page.goto('/');
  await page.locator('#open-maze').tap();
  await page.locator('[data-maze-mode="refresh"]').tap();
  await page.locator('#maze-start-run').tap();
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await expect(page.locator('#maze-trap-count')).toContainText('3 TRAPS');
  await expect(page.locator('.maze-touch-controls')).toBeVisible();
  await page.screenshot({ path: '.runtime/maze-repair2-mobile-board.png', fullPage: true });
  const fontSize = (selector) => page.locator(selector).first().evaluate((node) => Number.parseFloat(getComputedStyle(node).fontSize));
  expect(await fontSize('.maze-stat>span')).toBeGreaterThanOrEqual(11);
  expect(await fontSize('.maze-status')).toBeGreaterThanOrEqual(11);
  expect(await fontSize('.maze-board-tools')).toBeGreaterThanOrEqual(11);
  expect(await fontSize('.maze-touch-controls>p')).toBeGreaterThanOrEqual(11);
  expect(await fontSize('.maze-touch-actions button')).toBeGreaterThanOrEqual(14);
  const canvas = page.locator('#maze-board');
  const initial = await canvas.evaluate((node) => node.toDataURL());
  await page.locator('[data-maze-direction="right"]').tap();
  await expect.poll(() => canvas.evaluate((node) => node.toDataURL())).not.toBe(initial);
  await page.locator('#maze-zoom-in').tap();
  await expect.poll(() => canvas.evaluate((node) => Number.parseFloat(getComputedStyle(node).width))).toBeGreaterThan(320);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  await page.screenshot({ path: '.runtime/maze-repair2-mobile-zoom.png', fullPage: true });
  await page.locator('#maze-touch-pause').tap();
  await expect(page.locator('#maze-status-text')).toHaveText('PAUSED');
  const buttonBox = await page.locator('#maze-overlay-action').boundingBox();
  const viewportBox = await page.locator('#maze-board-viewport').boundingBox();
  expect(buttonBox.y + buttonBox.height).toBeLessThanOrEqual(viewportBox.y + viewportBox.height);
  await page.screenshot({ path: '.runtime/maze-repair2-mobile-pause.png', fullPage: true });
  await page.locator('#maze-overlay-action').tap();
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await page.locator('#maze-touch-restart').tap();
  await expect(page.locator('#maze-level')).toHaveText('01');
  await expect(page.locator('#maze-status-text')).toHaveText('IN THE MAZE');
  await page.locator('#maze-touch-home').tap();
  await expect(page.locator('#home')).toBeVisible();
  await expect(page.locator('#maze-view')).toBeHidden();
  expect(pageErrors).toEqual([]);
  await context.close();
});
